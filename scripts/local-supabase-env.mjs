/**
 * Write/refresh gitignored `.env.local` from local Supabase status + template.
 * Never touches hosted credentials in `.env`.
 */
import { spawnSync } from 'node:child_process';
import { writeFileSync, existsSync, renameSync, unlinkSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve('.');
const ENV_LOCAL = resolve(ROOT, '.env.local');
const ENV_LOCAL_OFF = resolve(ROOT, '.env.local.off');
const API_PORT = 55321;

/** Well-known local Supabase demo anon JWT (public; same for every `supabase start`). */
const LOCAL_ANON_KEY =
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0';

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

function readStatusEnv() {
  const result = spawnSync('supabase', ['status', '-o', 'env'], {
    encoding: 'utf8',
    shell: true,
  });
  const text = `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
  const api = text.match(/API_URL="([^"]+)"/)?.[1];
  const anon = text.match(/ANON_KEY="([^"]+)"/)?.[1];
  return { api, anon, ok: result.status === 0 && Boolean(api && anon) };
}

export function writeLocalEnv() {
  const status = readStatusEnv();
  const apiUrl = status.api ?? `http://127.0.0.1:${API_PORT}`;
  const anon = status.anon ?? LOCAL_ANON_KEY;

  if (!/127\.0\.0\.1|localhost/i.test(apiUrl)) {
    fail(`Refusing to write .env.local — API_URL is not local: ${apiUrl}`);
  }

  // Restore from .env.local.off if user previously ran dev:hosted
  if (!existsSync(ENV_LOCAL) && existsSync(ENV_LOCAL_OFF)) {
    renameSync(ENV_LOCAL_OFF, ENV_LOCAL);
  }

  const body = `# AUTO-GENERATED by npm run dev:local — DO NOT COMMIT
# Points the Expo bundler at the LOCAL Clash Supabase Docker stack.
# Remove/rename this file (npm run dev:hosted) to use hosted credentials from .env.
#
# Physical Android: adb reverse tcp:${API_PORT} tcp:${API_PORT}
# Sign in: dev@clash.local / clash-local-dev

EXPO_PUBLIC_SUPABASE_URL=${apiUrl}
EXPO_PUBLIC_SUPABASE_ANON_KEY=${anon}

# Dev-only: completed ranking-race chart without waiting for real snapshots.
# Set to 0 to use live Supabase trend history instead.
EXPO_PUBLIC_ARENA_TREND_DEMO=1
`;

  writeFileSync(ENV_LOCAL, body, 'utf8');
  console.log(`Wrote ${ENV_LOCAL}`);
  console.log(`  EXPO_PUBLIC_SUPABASE_URL=${apiUrl}`);
  if (!status.ok) {
    console.warn('Warning: supabase status failed — used fallback local URL/key. Is the stack running?');
  }
}

export function disableLocalEnv() {
  if (existsSync(ENV_LOCAL)) {
    if (existsSync(ENV_LOCAL_OFF)) unlinkSync(ENV_LOCAL_OFF);
    renameSync(ENV_LOCAL, ENV_LOCAL_OFF);
    console.log('Moved .env.local → .env.local.off (hosted .env will be used)');
  } else {
    console.log('No .env.local present — already using hosted/.env defaults');
  }
}

export function adbReverseSupabase() {
  const devices = spawnSync('adb', ['devices'], { encoding: 'utf8', shell: true });
  if (devices.status !== 0) {
    fail('adb not found. Install Android platform-tools and ensure adb is on PATH.');
  }
  const lines = (devices.stdout ?? '')
    .split(/\r?\n/)
    .filter((line) => line.includes('\tdevice'));
  if (lines.length === 0) {
    fail('No Android device connected (adb devices). Plug in USB and enable debugging.');
  }
  const rev = spawnSync(
    'adb',
    ['reverse', `tcp:${API_PORT}`, `tcp:${API_PORT}`],
    { encoding: 'utf8', shell: true },
  );
  if (rev.stdout) process.stdout.write(rev.stdout);
  if (rev.stderr) process.stderr.write(rev.stderr);
  if (rev.status !== 0) {
    fail(`adb reverse failed for port ${API_PORT}`);
  }
  console.log(`adb reverse tcp:${API_PORT} tcp:${API_PORT} OK`);
  console.log('Only the Kong API gateway port is forwarded (auth/rest/realtime/storage).');
}
